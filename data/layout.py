props, used = [], set()
for kind, owner, name, art, lat, lon in P:
    x, y = FORCE.get(name, tile(lat, lon))
    # nearest free land tile if taken or in the river
    best = None
    for r in range(4):
        for dy in range(-r, r + 1):
            for dx in range(-r, r + 1):
                nx, ny = x + dx, y + dy
                if abs(dx) + abs(dy) != r or not (0 <= nx < MW and 0 <= ny < MH): continue
                if (nx, ny) in used or (grid[ny][nx] in "~b" and name not in FORCE): continue
                best = best or (nx, ny)
        if best: break
    used.add(best); x, y = best
    grid[y][x] = "P"
    props.append({"x": x, "y": y, "kind": kind, "owner": owner, "name": name, "art": art})
    print(f"{name:22s} {x:2d},{y:2d}" + ("  moved" if (x, y) != tile(lat, lon) else ""))
rows = ["".join(r) for r in grid]
print("\n".join(rows))
