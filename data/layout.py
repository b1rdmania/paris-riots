# reachability check
import heapq
COST = {"foot": {"#": 2, "=": 1, "T": 1, "b": 1, "P": 1}, "wheels": {"=": 1, "T": 2, "b": 1, "P": 1}}
def reach(mt, sx, sy):
    seen = {(sx, sy)}; q = [(sx, sy)]
    while q:
        x, y = q.pop()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nx, ny = x + dx, y + dy
            if 0 <= nx < MW and 0 <= ny < MH and (nx, ny) not in seen and rows[ny][nx] in COST[mt]:
                seen.add((nx, ny)); q.append((nx, ny))
    return seen
for hq in [p for p in props if p["kind"] == "hq"]:
    for mt in ("foot", "wheels"):
        r = reach(mt, hq["x"], hq["y"])
        miss = [p["name"] for p in props if (p["x"], p["y"]) not in r]
        print(hq["name"], mt, "unreachable:", miss)
